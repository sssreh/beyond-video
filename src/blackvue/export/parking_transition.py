"""
Synthetic "parking footage skipped" transition clip for bv-export's
--include-parking option.

By default (--include-parking not given), a Parking-mode recording
strictly in the middle of a trip - flanked by other recordings on
both sides, see trip_export.py's _is_mid_trip_parking() - is left out
of front.mp4/rear.mp4/audio.aac and replaced by a short synthetic
clip instead: a still frame reading "PARKING FOOTAGE SKIPPED" for the
video assets, and matching silence for the audio asset, both exactly
PARKING_TRANSITION_DURATION_SECONDS long. Christer asked for the
audio to swap in matching silence too ("keeps stitch.mp4's audio in
sync"), so every substituted asset for the same recording has to
share that one duration.

The clip can't be a single static video file shipped once and reused
everywhere, because ffmpeg's concat demuxer (media.py's
concatenate_media()) stream-copies rather than re-encodes - every
source has to already match its neighbours' own resolution/frame
rate (video) or sample rate/channel layout/codec (audio) exactly,
and those vary by camera/archive. render_parking_transition_video()/
render_parking_transition_silence() below probe whichever real asset
they're standing in for and encode a placeholder to match it, and
ParkingTransitionCache reuses each rendered clip for the rest of the
trip whenever a later skipped recording happens to need the exact
same (width, height, frame_rate) or (codec, sample_rate, channels)
combination.

The still image itself (dark background, red "no parking" icon,
caption) is generated by render_parking_transition_image() below, or
supplied by Christer via --parking-transition-image - the same
"bundled default, overridable with your own picture" convention
--map-icon/--stitch-mirror-icon already use. It's deliberately an
image, not a pre-made video, so render_parking_transition_video() can
always encode it to match whatever resolution/frame rate this trip's
cameras happen to be running at, rather than needing to also match a
fixed frame rate baked into a pre-encoded override clip.

Copyright (C) 2026 Christer R. (sssreh)

SPDX-License-Identifier: GPL-3.0-or-later
"""

